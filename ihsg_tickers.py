@st.cache_data(ttl=86400)
def get_all_ihsg_tickers():
  """Mengembalikan daftar lengkap seluruh ticker saham IHSG (800+).

  Daftar di-cache agar instan & aman dari error internet.
  """
  # 1. Coba ambil pembaruan dinamis dari Github Dataset jika koneksi lancar
  try:
    url = "https://raw.githubusercontent.com/datasets/indonesia-stock-exchange/master/data/stock_code.csv"
    df = pd.read_csv(url)
    if "Ticker" in df.columns:
      dynamic_tickers = [
          f"{str(t).strip().upper()}.JK"
          for t in df["Ticker"]
          if len(str(t).strip()) == 4
      ]
    elif "Code" in df.columns:
      dynamic_tickers = [
          f"{str(t).strip().upper()}.JK"
          for t in df["Code"]
          if len(str(t).strip()) == 4
      ]

    dynamic_tickers = sorted(list(set(dynamic_tickers)))
    if len(dynamic_tickers) >= 500:
      return dynamic_tickers
  except Exception:
    pass

  # 2. Jika koneksi scraping eksternal terbatas, gunakan Master List 800+ Saham yang tersimpan
  return sorted(list(set(FULL_IHSG_MASTER)))
